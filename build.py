#!/usr/bin/env python3
"""TypePop build script: validate content JSON and inline it into site/js/data.js.

Usage:  python3 build.py        (run from ~/workspace/personality-test/)
"""
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent
CONTENT = ROOT / "content"
SITE_JS = ROOT / "site" / "js"

DIMS = ("EI", "SN", "TF", "JP")
ALL_TYPES = (
    "ENFP ENFJ ENTP ENTJ INFP INFJ INTP INTJ "
    "ESFP ESFJ ESTP ESTJ ISFP ISFJ ISTP ISTJ"
).split()


def fail(msg):
    print("BUILD FAILED:", msg, file=sys.stderr)
    sys.exit(1)


def load(name):
    p = CONTENT / name
    if not p.exists():
        fail(f"missing {p}")
    try:
        return json.loads(p.read_text(encoding="utf-8"))
    except json.JSONDecodeError as e:
        fail(f"{name} is not valid JSON: {e}")


def check_questions(qs):
    if not isinstance(qs, list) or len(qs) != 32:
        fail(f"questions.json must be a list of 32, got {len(qs) if isinstance(qs, list) else type(qs)}")
    seen = set()
    per_dim = {d: {d[0]: 0, d[1]: 0} for d in DIMS}
    for i, q in enumerate(qs):
        for f in ("id", "dim", "pole", "text"):
            if f not in q:
                fail(f"question #{i} missing field '{f}'")
        if q["id"] in seen:
            fail(f"duplicate question id {q['id']}")
        seen.add(q["id"])
        if q["dim"] not in DIMS:
            fail(f"{q['id']}: bad dim {q['dim']}")
        if q["pole"] not in q["dim"]:
            fail(f"{q['id']}: pole {q['pole']} not in dim {q['dim']}")
        for lang in ("en", "ko"):
            t = q["text"].get(lang, "")
            if not isinstance(t, str) or len(t.strip()) < 8:
                fail(f"{q['id']}: text.{lang} too short/missing")
        per_dim[q["dim"]][q["pole"]] += 1
    for d in DIMS:
        a, b = per_dim[d][d[0]], per_dim[d][d[1]]
        if a != 8 or b != 8:
            # require 8 questions per dim, balanced 4/4 per pole
            if a + b != 8 or a != 4 or b != 4:
                fail(f"dim {d}: need 8 questions balanced 4/4 per pole, got {a}/{b}")
    print(f"  questions: OK (32, balanced 4+4 per pole on each dim)")


def check_types(ts):
    if not isinstance(ts, list) or len(ts) != 16:
        fail(f"types.json must be a list of 16, got {len(ts) if isinstance(ts, list) else type(ts)}")
    codes = [t.get("code") for t in ts]
    if sorted(codes) != sorted(ALL_TYPES):
        fail(f"types.json must cover all 16 codes, got {codes}")
    for t in ts:
        for f in ("code", "name", "tagline", "desc", "strengths", "growth", "celebs"):
            if f not in t:
                fail(f"{t.get('code')}: missing field '{f}'")
        for f in ("name", "tagline", "desc"):
            for lang in ("en", "ko"):
                if not t[f].get(lang, "").strip():
                    fail(f"{t['code']}: {f}.{lang} missing")
        for f in ("strengths", "growth", "celebs"):
            for lang in ("en", "ko"):
                v = t[f].get(lang)
                if not isinstance(v, list) or len(v) < 2 or not all(isinstance(x, str) and x.strip() for x in v):
                    fail(f"{t['code']}: {f}.{lang} must be a list of 2+ strings")
    print(f"  types: OK (16 profiles, EN+KO)")


def main():
    print("TypePop build — validating content…")
    qs = load("questions.json")
    ts = load("types.json")
    check_questions(qs)
    check_types(ts)

    SITE_JS.mkdir(parents=True, exist_ok=True)
    out = SITE_JS / "data.js"
    payload = (
        "/* generated by build.py — do not edit directly */\n"
        "window.TP_QUESTIONS = "
        + json.dumps(qs, ensure_ascii=False)
        + ";\nwindow.TP_TYPES = "
        + json.dumps(ts, ensure_ascii=False)
        + ";\n"
    )
    out.write_text(payload, encoding="utf-8")
    print(f"  wrote {out} ({len(payload)//1024} KB)")
    print("BUILD OK ✔")


if __name__ == "__main__":
    main()
